#!/usr/bin/env python3
import argparse
import json
import os
import sys
from pathlib import Path

CATEGORIES = ("high-risk", "ordinary", "mechanical", "verification")


def load_catalog(path=None):
    if path is None:
        path = (
            Path(__file__).resolve().parent.parent
            / "references"
            / "catalog.json"
        )
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def config_dir():
    if "SHIPPY_CONFIG_DIR" in os.environ:
        return Path(os.environ["SHIPPY_CONFIG_DIR"])
    return Path.home() / ".config" / "shippy"


def default_config(catalog):
    routes = []
    fallbacks = []
    for pid, pinfo in catalog.get("providers", {}).items():
        d = pinfo.get("default")
        if d == "route":
            routes.append(pid)
        elif d == "fallback":
            fallbacks.append(pid)
    return {"routes": routes, "fallbacks": fallbacks, "perCategory": 4}


def load_config(catalog, path=None):
    if path is not None:
        cfg_path = Path(path)
    else:
        cfg_path = config_dir() / "t3.json"

    if not cfg_path.is_file():
        return default_config(catalog)

    try:
        with open(cfg_path, "r", encoding="utf-8") as f:
            raw = json.load(f)
    except Exception:
        return default_config(catalog)

    known_providers = catalog.get("providers", {})

    routes = []
    seen_routes = set()
    paid_from_routes = []
    seen_paid_from_routes = set()
    for p in raw.get("routes", []):
        if p not in known_providers:
            sys.stderr.write(f"Warning: unknown provider '{p}'\n")
            continue
        if known_providers[p].get("tier") == "paid":
            if p not in seen_paid_from_routes:
                seen_paid_from_routes.add(p)
                paid_from_routes.append(p)
            continue
        if p not in seen_routes:
            seen_routes.add(p)
            routes.append(p)

    fallbacks = []
    seen_fallbacks = set()
    for p in raw.get("fallbacks", []):
        if p not in known_providers:
            sys.stderr.write(f"Warning: unknown provider '{p}'\n")
            continue
        if p in seen_routes:
            continue
        if p not in seen_fallbacks:
            seen_fallbacks.add(p)
            fallbacks.append(p)

    for p in paid_from_routes:
        if p not in seen_fallbacks:
            seen_fallbacks.add(p)
            fallbacks.append(p)

    per_cat = raw.get("perCategory", 4)
    if not isinstance(per_cat, int) or isinstance(per_cat, bool):
        per_cat = 4
    else:
        per_cat = max(1, min(8, per_cat))

    return {"routes": routes, "fallbacks": fallbacks, "perCategory": per_cat}


def build_routes(catalog, config):
    routes_enabled = set(config.get("routes", []))
    per_category = config.get("perCategory", 4)
    providers = catalog.get("providers", {})
    result = {}

    for cat in CATEGORIES:
        free_models = []
        for idx, model in enumerate(catalog.get("models", [])):
            prov = model["provider"]
            if (
                prov in routes_enabled
                and providers.get(prov, {}).get("tier") != "paid"
                and cat in model.get("ranks", {})
            ):
                free_models.append((model["ranks"][cat], idx, model))
        free_models.sort(key=lambda x: (x[0], x[1]))
        free_selected = [x[2] for x in free_models[:per_category]]

        fallback_selected = []
        for pid in config.get("fallbacks", []):
            prov_models = []
            for idx, model in enumerate(catalog.get("models", [])):
                if model["provider"] == pid and cat in model.get("ranks", {}):
                    prov_models.append((model["ranks"][cat], idx, model))
            if prov_models:
                prov_models.sort(key=lambda x: (x[0], x[1]))
                fallback_selected.append(prov_models[0][2])

        result[cat] = {"free": free_selected, "fallback": fallback_selected}

    return result


def _format_entry(catalog, model):
    provider_id = model["provider"]
    pinfo = catalog.get("providers", {}).get(provider_id, {})
    options_str = json.dumps(model.get("options", {}), separators=(",", ":"))
    entry = f"{provider_id}:{model['id']} {options_str}"

    pools = pinfo.get("pools", {})
    pool_found = None
    for pool_name, model_ids in pools.items():
        if model["id"] in model_ids:
            pool_found = f" [pool {provider_id}/{pool_name}]"
            break
    if pool_found is None and pinfo.get("sharedPool"):
        pool_found = f" [pool {provider_id}]"

    if pool_found:
        entry += pool_found

    if pinfo.get("tier") == "limited":
        entry += " [limited]"

    return entry


def render_routes(catalog, routes):
    lines = [
        "# shippy-t3 routes",
        "Generated by scripts/configure.py; rerun it to change. Try free routes left to right, then fallbacks in order. [pool X]: models sharing quota pool X. [limited]: small or unclear free allowance.",
        "",
    ]

    for cat in CATEGORIES:
        cat_routes = routes.get(cat, {"free": [], "fallback": []})
        free_models = cat_routes.get("free", [])
        fallback_models = cat_routes.get("fallback", [])

        if free_models:
            free_part = " > ".join(_format_entry(catalog, m) for m in free_models)
        else:
            free_part = "none"

        if fallback_models:
            fallback_part = " > ".join(
                _format_entry(catalog, m) for m in fallback_models
            )
        else:
            fallback_part = "none"

        lines.append(f"- {cat}: {free_part} | fallback: {fallback_part}")

    return "\n".join(lines) + "\n"


def save(catalog, config, directory=None):
    if directory is None:
        directory = config_dir()
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)

    json_path = directory / "t3.json"
    md_path = directory / "t3-routes.md"

    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(config, f, indent=2)
        f.write("\n")

    routes = build_routes(catalog, config)
    rendered = render_routes(catalog, routes)
    with open(md_path, "w", encoding="utf-8") as f:
        f.write(rendered)

    return (json_path, md_path)


def _interactive_loop(catalog, config):
    providers_list = list(catalog.get("providers", {}).items())

    while True:
        for idx, (pid, pinfo) in enumerate(providers_list, 1):
            name = pinfo.get("name", pid)
            tier = pinfo.get("tier", "")
            note = pinfo.get("note", "")
            if pid in config["routes"]:
                status = "route"
            elif pid in config["fallbacks"]:
                status = "fallback"
            else:
                status = "off"
            print(f"{idx}. {name} [{status}] {tier} - {note}")

        if config["fallbacks"]:
            fb_names = [
                catalog["providers"][p].get("name", p)
                for p in config["fallbacks"]
                if p in catalog.get("providers", {})
            ]
            fb_order_str = " > ".join(fb_names) if fb_names else "none"
        else:
            fb_order_str = "none"

        print(f"Fallback order: {fb_order_str}")
        print(f"Routes per category: {config['perCategory']}")
        print(
            "<n> cycle route/fallback/off, u <n> move fallback earlier, k <1-8> routes per category, p preview, s save, q quit"
        )

        try:
            line = input().strip()
        except (EOFError, KeyboardInterrupt):
            return 0

        if not line:
            print("?")
            continue

        if line == "q":
            return 0
        elif line == "p":
            routes = build_routes(catalog, config)
            sys.stdout.write(render_routes(catalog, routes))
        elif line == "s":
            p1, p2 = save(catalog, config)
            print(p1)
            print(p2)
            return 0
        elif line.isdigit():
            n = int(line)
            if 1 <= n <= len(providers_list):
                pid, pinfo = providers_list[n - 1]
                if pid in config["routes"]:
                    config["routes"].remove(pid)
                    if pid not in config["fallbacks"]:
                        config["fallbacks"].append(pid)
                elif pid in config["fallbacks"]:
                    config["fallbacks"].remove(pid)
                else:
                    if pinfo.get("tier") == "paid":
                        if pid not in config["fallbacks"]:
                            config["fallbacks"].append(pid)
                    else:
                        config["routes"].append(pid)
            else:
                print("?")
        elif line.startswith("u"):
            rest = line[1:].strip()
            if rest.isdigit():
                n = int(rest)
                if 1 <= n <= len(providers_list):
                    pid, _ = providers_list[n - 1]
                    if pid in config["fallbacks"]:
                        idx = config["fallbacks"].index(pid)
                        if idx > 0:
                            config["fallbacks"][idx], config["fallbacks"][idx - 1] = (
                                config["fallbacks"][idx - 1],
                                config["fallbacks"][idx],
                            )
                    else:
                        print("?")
                else:
                    print("?")
            else:
                print("?")
        elif line.startswith("k"):
            rest = line[1:].strip()
            if rest.isdigit():
                val = int(rest)
                if 1 <= val <= 8:
                    config["perCategory"] = val
                else:
                    print("?")
            else:
                print("?")
        else:
            print("?")


def main(argv=None):
    if argv is None:
        argv = sys.argv[1:]

    parser = argparse.ArgumentParser(
        description="Configure shippy-t3 provider routing"
    )
    parser.add_argument(
        "--print",
        dest="print_routes",
        action="store_true",
        help="Print rendered routes",
    )
    parser.add_argument(
        "--defaults", action="store_true", help="Use default config"
    )
    args = parser.parse_args(argv)

    catalog = load_catalog()

    if args.print_routes:
        if args.defaults:
            config = default_config(catalog)
        else:
            config = load_config(catalog)
        routes = build_routes(catalog, config)
        sys.stdout.write(render_routes(catalog, routes))
        return 0

    if args.defaults:
        config = default_config(catalog)
        p1, p2 = save(catalog, config)
        print(p1)
        print(p2)
        return 0

    if not sys.stdin.isatty():
        sys.stderr.write(
            "configure.py needs a terminal; use --print to preview routes\n"
        )
        return 2

    config = load_config(catalog)
    return _interactive_loop(catalog, config)


if __name__ == "__main__":
    sys.exit(main())
